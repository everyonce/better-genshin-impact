"""Construct complete serialized v2 boundaries during a separately authorized inert cohort.

The retained legacy combined-reply witness supplies actual existing telemetry,
receipts, capture and readiness fields. V2 fixtures add the new bounded grammar.
This proves finite serialized data, not Python RSS, numerical tensor memory,
physical input, schedule feasibility or an operational enable path.
"""
import hashlib
from pathlib import Path

import step_application_protocol as p
import step_application_protocol_v2 as v2
from _step_application_v2_fixtures import QueuedFixture
from native_history_feedback import FeedbackError


def construct(output):
    """Retain actual 32-slot known/failure fixtures and every generated byte witness."""
    output = Path(output); output.mkdir(parents=True, exist_ok=False)
    files = []
    def save(name, raw, cap):
        """Write only caller-owned evidence with its actual byte count and hash."""
        p.require(type(raw) is bytes and len(raw) <= cap, 'v2_capacity_bound')
        (output/name).write_bytes(raw)
        files.append(dict(name=name, bytes=len(raw), sha256=hashlib.sha256(raw).hexdigest(), cap=cap))

    f = QueuedFixture(wide=True)
    all_terminals = []
    for index in range(32):
        f.identity['frameId'] = p.MAX_INT-32+index
        f.runtime.keys = ['W','A','LBUTTON','RBUTTON','MBUTTON','RSHIFT'] if index%2 == 0 else ['S','D','E','Q','R','F']
        observed = 0.0 if index == 0 else 20.0+50*(index-1)
        f.propose(observed=observed)
        before = p.decode(p.canonical(f.tracked))
        bound = f.wire['stepApplication']['binding']
        p.require(v2.reservation_byte_bound(bound, f.intake.config, before, index+1) <= p.RECORD_BYTES,
                  'v2_actual_reservation_bound')
        if index == 0:
            f.dispatch(applied=True)
        else:
            f.dispatch(admitted=observed+10)
            previous = f.rows[-1]; current = f.application()
            term = f.handoff(previous, current); all_terminals.append(term)
            if index == 31:
                # The maximum pending boundary keeps P unresolved and Q under its original lease.
                f.status()
                save('pending-owner.json', f.owner.metadata(), 65536)
                save('pending-coordinator.json', f.coordinator.metadata(), 65536)
                save('pending-ledger.json', f.intake.ledger.snapshot(cutoff_client_ns=3000), 512*1024)
                p.require(f.runtime.commits == 31 and f.owner._leased and f.owner._unresolved is not None
                          and f.owner._prepared is not None, 'v2_two_owner_boundary')
            f.status(terms=[term])
    final = f.terminal(); all_terminals.append(final); f.status(terms=[final], closed=True)
    p.require(len(f.intake.ledger._proposals) == len(f.intake.ledger._records) == len(f.intake.ledger._terminals) == 32
              and f.runtime.commits == f.runtime.prepares == 32 and f.runtime.restores == 0,
              'v2_complete_cardinality')
    p.require(not f.intake.ledger.proposal_capacity() and not f.owner._leased and f.owner._unresolved is None,
              'v2_final_closed_known')
    save('closed-owner.json', f.owner.metadata(), 65536)
    save('closed-coordinator.json', f.coordinator.metadata(), 65536)
    save('closed-dispositions.json', f.intake.disposition_metadata(), 16384)
    save('closed-ledger.json', f.intake.ledger.snapshot(cutoff_client_ns=3000), 512*1024)
    request = p.decode(p.canonical(f.wire, 65536), 65536)
    request['stepApplicationsAck'] = dict(version=2, channelId=f.intake.config['channelId'], through=32,
        terminalRequestIds=[row['binding']['requestId'] for row in all_terminals[-4:]])
    save('queued-request-and-ack.json', p.canonical(request,65536), 65536)

    legacy_path = Path(__file__).resolve().parent/'fixtures/step_application/maximum-combined-h02.json'
    legacy_bytes = legacy_path.read_bytes(); combined = p.decode(legacy_bytes, 4*1024*1024)
    # The last four applications permit the immediately preceding four handoff
    # terminals. The earlier predecessor application is retained/ACKed already.
    combined['stepApplications'] = f.batch(closed=True, ack=28)
    combined['stepApplicationTerminals'] = all_terminals[27:31]
    combined_raw = p.canonical(combined, 4*1024*1024)
    save('combined-frame-four-plus-four.json', combined_raw, 4*1024*1024)
    shared = legacy_path.parent/'queued_v2'
    reserved = p.decode((shared/'record-reservation-admitted-v2.json').read_bytes(),65536)
    terminal = p.decode((shared/'terminal-reservation-v2.json').read_bytes(),65536)
    conservative = p.decode(legacy_bytes,4*1024*1024)
    # Independent longest outer channel preserves the conservative C# header width.
    conservative['stepApplications'] = dict(version=2,channelId='\u0080'*64,acknowledgedThrough=0,
        nextReservedSequence=33,authorityLost=False,closedForSubmission=True,unpublished=0,records=[reserved]*4)
    conservative['stepApplicationTerminals'] = [terminal]*4
    conservative_raw = p.canonical(conservative,4*1024*1024)
    p.require(len(conservative_raw)==1886979 and hashlib.sha256(conservative_raw).hexdigest()==
        '44a8026981d1f28fef3e5dc8354fed5f26a1311fd190d0e84d0d1d295dbbf17d','shared_conservative_header')
    save('combined-reservation-witness.json',conservative_raw,4*1024*1024)
    for row in combined['stepApplications']['records']:
        v2.validate_record(row, f.intake.config)
    for term in combined['stepApplicationTerminals']:
        v2.validate_terminal(term, f.intake.config)
    # Adding all new maxima to the full old header is deliberately conservative:
    # the old application extension remains counted in this upper-bound sum.
    upper = len(legacy_bytes) + 4*8192 + 4*4096 + 2048 + 512 + 65536
    p.require(len(combined_raw)<=upper and len(conservative_raw)<=upper<=4*1024*1024, 'v2_combined_upper_bound')

    failed = QueuedFixture(); predecessor = failed.published_p_pending_q(); successor = failed.application()
    class RetainedFailure(Exception):
        """Maximum escaped primary failure text exercises actual retained failure metadata."""
    def fail(*args):
        """Fail at the inherited final-ticket seam, after its actual lease release."""
        raise RetainedFailure('\x01'*512)
    failed.intake.ledger.complete_native_ticket = fail
    try:
        failed.status(terms=[failed.handoff(predecessor, successor)])
    except FeedbackError:
        pass
    else:
        raise AssertionError('v2_expected_finalization_failure')
    save('failed-owner.json', failed.owner.metadata(), 65536)
    save('failed-coordinator.json', failed.coordinator.metadata(), 65536)
    p.require(not failed.owner._leased and failed.owner._publication is not None
              and failed.owner._publication is failed.owner._unresolved, 'v2_failed_owner_retained')
    summary = dict(schema='native-queued-v2-capacity-v1', files=files,
        actualAttempts=32, actualApplications=32, actualTerminals=32, recordsPerReply=4, terminalsPerReply=4,
        completePendingAndClosedStates=True, failureRetained=True, failureLeaseReleasedBeforeFinalTicket=True,
        combinedReplyBytes=len(combined_raw), legacyCombinedBytes=len(legacy_bytes),
        sharedReservationHeaderBytes=len(conservative_raw),sharedReservationHeaderSha256=hashlib.sha256(conservative_raw).hexdigest(),
        combinedConservativeBytes=upper, combinedLimitBytes=4*1024*1024,
        retainedCanonicalPayloadBytes=704000+32*2048+32*256,
        addedCanonicalPayloads=dict(admissions=32*2048, originalSourceScalars=32*256),
        perRevisionItemBytes=2048, unchangedLimits=dict(request=65536, application=8192, terminal=4096,
            snapshot=512*1024, ownerMetadata=65536, coordinatorMetadata=65536, dispositions=16384),
        limitations=['All generated bytes are retained; no runtime or physical-input claim.',
            'The canonical-payload subtotal excludes Python object overhead, tracebacks, transient parsing and native tensors.',
            'No claim that every independent text maximum fits each record; the binding/application/terminal gates remain authoritative.',
            'C# production-serializer maximum fixtures and actual cadence remain independent qualification gates.'])
    save('capacity.json', p.canonical(summary,65536), 65536)
    return summary
